def run_primary_disentanglement() -> Dict[str, Any]:
    """
    Saves the primary and secondary datasets and outputs summary metrics.
    """
    RAW_DATA_DIR.mkdir(parents=True, exist_ok=True)
    PROCESSED_DATA_DIR.mkdir(parents=True, exist_ok=True)

    df_primary = build_primary_experimental_corpus()
    df_secondary = build_secondary_review_dataset()

    df_primary.to_csv(PRIMARY_CSV_PATH, index=False)
    df_secondary.to_csv(SECONDARY_REVIEW_CSV_PATH, index=False)

    # Build updated provenance ledger
    ledger_records = []
    for _, row in df_primary.iterrows():
        ledger_records.append({
            "data_point_id": row["data_point_id"],
            "source_uid": row["source_uid"],
            "citation_short": row["citation_short"],
            "doi": row["doi"],
            "provenance_location": row["provenance_location"],
            "contact_metal": row["contact_metal"],
            "is_vdw": row["is_vdw_or_depinned_contact"],
            "layer_count": row["layer_count"],
            "reported_rc_ohm_um": row["contact_resistance_rc_ohm_um"],
            "rc_uncertainty_pct": row["rc_uncertainty_pct"],
            "measured_sbh_ev": row["measured_sbh_ev"],
            "sbh_measurement_method": row["sbh_measurement_method"],
            "annealing_status": row["post_annealing_status"],
            "vacuum_provenance": row["vacuum_provenance"],
            "carrier_density_provenance": row["carrier_density_provenance"],
            "is_primary_experimental": True
        })

    df_ledger = pd.DataFrame(ledger_records)
    df_ledger.to_csv(EXPANDED_LEDGER_CSV_PATH, index=False)

    return {
        "status": "success",
        "primary_records_count": len(df_primary),
        "primary_independent_sources": int(df_primary["source_uid"].nunique()),
        "secondary_review_records_count": len(df_secondary),
        "metals_covered": sorted(df_primary["contact_metal"].unique().tolist()),
        "primary_csv": str(PRIMARY_CSV_PATH),
        "secondary_csv": str(SECONDARY_REVIEW_CSV_PATH),
        "ledger_csv": str(EXPANDED_LEDGER_CSV_PATH)
    }


if __name__ == "__main__":
    res = run_primary_disentanglement()
    print("Primary literature disentanglement complete.")
    print(f"Total Primary Observations: {res['primary_records_count']} across {res['primary_independent_sources']} independent sources.")
    print(f"Metals: {res['metals_covered']}")
